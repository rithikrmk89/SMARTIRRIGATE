import numpy as np
import pandas as pd
from pathlib import Path
from typing import Optional

# FAO-56 Reference Crop Coefficients (Kc) during mid-season peak growth stage
CROP_COEFFICIENTS = {
    "Wheat": 1.15,
    "Rice": 1.25,
    "Maize": 1.20,
    "Cotton": 1.15,
    "Tomato": 1.05,
    "Sugarcane": 1.30,
    "Potato": 1.10,
    "Barley": 1.00
}

# Soil texture water holding and infiltration adjustment factors
SOIL_FACTORS = {
    "Sandy": 1.18,  # High percolation loss, lower water holding capacity
    "Loamy": 1.00,  # Standard reference agronomic loamy soil
    "Clay": 0.88,   # High water retention, lower irrigation frequency
    "Silt": 0.94,   # Fine granular, high available water capacity
    "Peaty": 0.90   # High organic matter, strong sponge retention
}


def generate_irrigation_dataset(
    num_samples: int = 1200,
    random_seed: int = 42,
    output_path: Optional[Path] = None,
    include_outliers: bool = False
) -> pd.DataFrame:
    """
    Generates a realistic synthetic agronomic dataset based on the FAO-56
    Penman-Monteith Evapotranspiration framework.

    NOTE & DISCLAIMER:
    All records generated by this function are synthetic approximations designed
    for algorithm benchmarking, local demonstrations, and reproducible testing.
    They are NOT direct physical IoT sensor readings. Real-world deployments should
    ingest localized agro-meteorological station records.
    """
    np.random.seed(random_seed)

    crops = list(CROP_COEFFICIENTS.keys())
    soils = list(SOIL_FACTORS.keys())

    # Categorical distributions
    crop_samples = np.random.choice(crops, size=num_samples)
    soil_samples = np.random.choice(soils, size=num_samples)

    # Environmental continuous distributions
    temperature = np.random.uniform(18.0, 39.0, size=num_samples)  # °C
    humidity = np.random.uniform(25.0, 85.0, size=num_samples)      # %
    soil_moisture = np.random.uniform(15.0, 75.0, size=num_samples) # %
    rainfall = np.random.exponential(scale=6.0, size=num_samples)   # mm
    rainfall = np.where(rainfall < 1.0, 0.0, rainfall)             # dry days
    sunlight_hours = np.random.uniform(5.0, 11.5, size=num_samples) # hours/day
    wind_speed = np.random.uniform(4.0, 26.0, size=num_samples)     # km/h

    # Field area (hectares) for farm scaling calculations
    area_hectares = np.random.choice([0.5, 1.0, 1.5, 2.0, 3.5, 5.0, 10.0], size=num_samples)

    water_demands = []

    for i in range(num_samples):
        c = crop_samples[i]
        s = soil_samples[i]
        t = temperature[i]
        h = humidity[i]
        sm = soil_moisture[i]
        r = rainfall[i]
        sun = sunlight_hours[i]
        w = wind_speed[i]

        kc = CROP_COEFFICIENTS[c]
        soil_f = SOIL_FACTORS[s]

        # Empirical Penman-Monteith ET0 estimate (mm/day)
        et0 = (0.09 * t) + (0.16 * sun) + (0.02 * w) - (0.035 * (h - 50.0)) + 0.8
        et0 = max(1.5, et0)

        # Crop Evapotranspiration
        etc = kc * et0 * soil_f

        # Soil moisture deficit adjustment (optimal moisture ~55-60%)
        moisture_deficit = ((55.0 - sm) / 100.0) * 4.2

        # Effective precipitation deduction (FAO USDA-SCS method)
        eff_rain = 0.8 * (r - 2.0) if r > 2.0 else 0.0

        # Net required irrigation water demand (mm/day)
        net_demand = etc + moisture_deficit - eff_rain

        # Natural environmental stochastic variation (Gaussian noise)
        noise = np.random.normal(0.0, 0.28)
        daily_demand = max(0.0, round(float(net_demand + noise), 2))

        water_demands.append(daily_demand)

    df = pd.DataFrame({
        "crop_type": crop_samples,
        "soil_type": soil_samples,
        "soil_moisture_pct": np.round(soil_moisture, 1),
        "temperature_c": np.round(temperature, 1),
        "humidity_pct": np.round(humidity, 1),
        "rainfall_mm": np.round(rainfall, 1),
        "sunlight_hours": np.round(sunlight_hours, 1),
        "wind_speed_kmh": np.round(wind_speed, 1),
        "area_hectares": area_hectares,
        "water_demand_mm_day": water_demands,
        "data_source": "synthetic_fao56_demo"
    })

    if include_outliers:
        # Add 1% anomaly rows to test cleaning/robustness
        outlier_indices = np.random.choice(num_samples, size=max(1, int(num_samples * 0.01)), replace=False)
        df.loc[outlier_indices, "water_demand_mm_day"] *= 2.2

    if output_path:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(output_path, index=False)

    return df
